"""The nano duck's parts list and build order: MILLI_RECIPE=nano python -I tools/make_docs.py -> docs/nano/BOM.md, docs/nano/ASSEMBLY.md.

From spec/robot_nano.json (its parts, screws and order: spec/nano_duck.py), spec/parts_nano.json (the printed parts' volumes: tools/export_prints.py) and the parts' masses (tools/mass_model.py).
docs/nano/WIRING.md is written by hand. Every source named here was opened on 2026-11-06; what wasn't is marked.
"""
import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import checks as C  # noqa: E402
import geom as G  # noqa: E402
import mass_model as MM  # noqa: E402

BOUGHT = {
    # part: (what to buy, source, note)
    'Pi Zero 2 W': ('Raspberry Pi Zero 2 W, with a microSD card', 'raspberrypi.com/products/raspberry-pi-zero-2-w/ (65 x 30 mm; no mass given there: 11 g is the repo\'s figure)', 'its 13 servo signals from its GPIO (docs/nano/WIRING.md)'),
    'battery': ('2S LiPo, 300 mAh, Tattu 75C (7.6 V, a high-voltage pack)', 'genstattu.com/ta-75c-300-2s1p-jst.html: 45 x 16 x 12 mm, 16 g, 75C, JST-PHR plug, JST-XHR balance lead', 'cut the PH plug off and fit an XT30: it carries up to 7.5 A'),
    'L 5 V regulator': ('Pololu D24V50F5, 5 V 5 A step-down', 'pololu.com/product/2851: 6-38 V in, 17.8 x 20.3 x 8.8 mm, 3.0 g; at 5 A it wants 6.2 V in', 'the left leg, the neck servo and the Pi'),
    'R 5 V regulator': ('Pololu D24V50F5, 5 V 5 A step-down', 'as above', 'the right leg, head pitch and beak'),
    'IMU': ('Adafruit MPU-6050 6-DoF, STEMMA QT (product 3886)', 'adafruit.com/product/3886: 26.0 x 17.8 x 4.6 mm, 1.8 g, I2C', 'on the Pi\'s I2C (GPIO 2, 3)'),
    'servo header board': ('a 2.54 mm perfboard, 13 x 3-pin male headers, the + and - rows cut in two groups', 'none: 34 x 16 mm, 4 g estimated', 'each servo\'s own lead plugs in; 13 signal wires to the Pi'),
}


def write(s):
    out = G.out_path('docs')
    os.makedirs(out, exist_ok=True)
    S = C.Solids(s)
    inert = MM.link_inertials(s, S)
    total = sum(v[0] for v in inert.values())
    by_mat = collections.Counter()
    for ln in s['links']:
        for name, mat, m, com, I in MM.parts(s, S, ln):
            by_mat[mat] += m
    acts = collections.Counter(j['act'] for j in s['joints'])
    where = collections.defaultdict(list)
    for j in s['joints']:
        where[j['act']].append(j['name'])
    A = s['actuators']
    screws = collections.Counter()
    for l in s['links'].values():
        for g in l['geoms']:
            if 'fast' not in g:
                continue
            n = g['name']
            kind = ("the servo's own ear screw (in its bag)" if ' cradle screw ' in n else "the servo's own horn screw (in its bag)" if n.endswith('horn screw')
                    else f"M2 x {g['fast']['L'] * 1000:.0f} pan head, self-tapping into PLA")
            screws[kind] += 1
    P = json.load(open(G.parts_path(), encoding='utf-8'))['parts']
    L = ['# The nano duck: parts', '', 'Generated by `tools/nano_docs.py` (`MILLI_RECIPE=nano python -I tools/make_docs.py`) from `spec/nano_duck.py`: don\'t edit by hand. Wiring: [WIRING.md](WIRING.md). Build order: [ASSEMBLY.md](ASSEMBLY.md).', '',
         f"**{len(s['joints'])} joints, {total * 1000:.0f} g** from every part's material (`tools/mass_model.py`), "
         f"{', '.join(f'{k} {v * 1000:.0f} g' for k, v in sorted(by_mat.items(), key=lambda kv: -kv[1]))}, and {MM.WIRING * 100:.0f} % of each link for wires and tape. Nothing has been printed or weighed.", '',
         '## Servos', '', '| Qty | Servo | Joints | Stall at about 5 V (design figure) | Mass | Source |', '|---|---|---|---|---|---|']
    for k, n in acts.items():
        a = A[k]
        src = 'towerpro.com.tw/product/sg90-7/ (1.8 kg.cm at 4.8 V) and docs.m5stack.com/en/accessory/SG90_Servo (1.6 at 4.8 V): the lower' if k == 'SG90' else 'towerpro.com.tw/product/mg90s-3/ (1.8 kg.cm at 4.8 V, 2.2 at 6.6 V)'
        L.append(f"| {n} | {a.get('name', k)} | {', '.join(where[k])} | {a['peak_nm']:.3f} N m | {a['mass'] * 1000:.1f} g | {src} |")
    L += ['', 'The MG90S, metal geared, where a joint carries the duck in a step: knees and hip roll (`tools/nano_sweep.py`). At 4.8 V it is no stronger than an SG90 by TowerPro\'s own figures; it is less likely to strip a gear. '
          'Stall current: an SG90 360 mA measured (protosupplies.com/product/servo-motor-micro-sg90/), up to about 650 mA listed (pcboard.ca/sg90-servo); an MG90S 700 mA measured (protosupplies.com/product/servo-motor-micro-mg90s/).', '',
          '## Electronics', '', '| Qty | Part | Source | What for |', '|---|---|---|---|']
    have = {p[0] for p in s['parts']}
    for k, (what, src, note) in BOUGHT.items():
        if k not in have:
            continue
        if k == 'R 5 V regulator':
            continue
        q = 2 if k == 'L 5 V regulator' else 1
        L.append(f'| {q} | {what} | {src} | {note if q == 1 else "one per side: " + note + "; " + BOUGHT["R 5 V regulator"][2]} |')
    L += ['| 1 | XT30 plug pair, 20 AWG silicone wire for the 5 V buses, 28-30 AWG for the 13 signals | not sourced | counted in the wiring allowance |', '',
          '## Screws', '', '| Qty | Screw |', '|---|---|']
    for k, n in screws.items():
        L.append(f'| {n} | {k} |')
    L += ['', 'The 2 ear screws and the horn screw of each servo come in its bag. Their sizes are not on the makers\' pages: about M2 is an estimate. Check them against your servos.', '',
          '## Printed parts', '', f"{sum(1 for v in P.values())} STLs in [prints/nano/](../../prints/nano/README.md), left and right, from the spec's shapes (no Fusion model: their corners are sharp). PLA unless marked; the soles TPU 95A.", '',
          '| Part | Volume (cm3) | Material |', '|---|---|---|']
    for name, v in sorted(P.items()):
        L.append(f"| {name} | {v['volume_cm3']:.1f} | {'TPU 95A' if v['material'] == 'tpu' else 'PLA'} |")
    L += ['', 'The body shell and hood print with 1.2 mm walls (3 lines of a 0.4 mm nozzle): their masses are from that wall; the collision checks give every shell 2 mm.', '',
          '## Not verified', '',
          '- **The SG90\'s shape:** case length, width, height to the tower and spline, across the ears and to their underside are TowerPro\'s; the case\'s top (22.5 mm), the ears\' thickness, the ear holes (2.0 mm at +/-14.4 mm) and the shaft\'s offset (5.6 mm) are read off a drawing that is not to scale. The MG90S is taken as the same shape. Measure one before printing.',
          '- **Torque:** the stall figures are the makers\', at about 5 V. A real micro servo sags well before it stalls, and these are static estimates (`tools/checks.py`, `tools/nano_sweep.py`).',
          '- **The 21T spline:** the teeth aren\'t modelled; see prints/nano/README.md.',
          '- **Masses:** every printed part from its volume; the Pi\'s 11 g is the repo\'s figure, the header board 4 g a guess.',
          '- **Strength:** LOAD in `tools/buildable.py` is a beam estimate, not FEA. Nothing has been printed, built or walked.', '']
    open(os.path.join(out, 'BOM.md'), 'w', encoding='utf-8').write('\n'.join(L))
    A_ = ['# How to build the nano duck', '', 'Generated by `tools/nano_docs.py` from the order in `spec/nano_duck.py`, which `tools/assembly.py` checks: every part has a straight way in, every screw a key\'s reach and a bite. '
          'The right leg is the left\'s mirror. Set each servo to mid-range (1500 us) before its horn goes on. Parts: [BOM.md](BOM.md); wiring: [WIRING.md](WIRING.md).', '']
    for sec in s['assembly']:
        A_ += [f"## {sec['title']}", '']
        if sec['on']:
            A_ += [f"On: {', '.join(sec['on'])}.", '']
        for k, (cap, items, pats) in enumerate(sec['steps'], 1):
            parts = ', '.join(p[1:] + ' (built above)' if p.startswith('@') else p for p, _ in items)
            A_.append(f'{k}. {cap}' + (f' ({parts})' if parts else ''))
        A_.append('')
    open(os.path.join(out, 'ASSEMBLY.md'), 'w', encoding='utf-8').write('\n'.join(A_))
    return 'docs/nano/BOM.md, docs/nano/ASSEMBLY.md'

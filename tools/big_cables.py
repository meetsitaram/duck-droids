"""The big duck's actuator cables: does each one's harness reach the boards? A route per actuator, listed, not drawn: python -I tools/big_cables.py -> docs/big/CABLES.md

Each RobStride harness is 310 mm to its XT30 and 40 mm more of CAN pair to its GH plug (docs/big/WIRING.md). The route here: from where the cable leaves the actuator, to each joint it
crosses on the way up to the trunk, near that joint's axis (where a loop moves least), then to the nearest face of the computer and power board box on the deck. Straight lines between those points,
plus at each joint crossed the slack for its range, wrapping at the loop's bend radius (range x radius). So it's a lower bound for a real route, which follows plates and turns corners.

Bend radius: assumed, as RobStride's harness rating hasn't been read. 4 x its 7.3 mm diameter (30 mm) where it's tied down, 10 x (75 mm) in a loop that moves.
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = json.load(open(os.path.join(ROOT, 'spec', 'robot_big.json'), encoding='utf-8'))
HARNESS, CAN = 0.310, 0.040
OD = 0.0073
R_STATIC, R_LOOP = 4 * OD, 10 * OD
links, joints = spec['links'], {j['child']: j for j in spec['joints']}
board = next(g for g in links['trunk']['geoms'] if g['name'] == 'computer and power boards')
blo = [board['c'][i] - board['size'][i] / 2 for i in range(3)]
bhi = [board['c'][i] + board['size'][i] / 2 for i in range(3)]
AX = {'x': (1, 0, 0), 'y': (0, 1, 0), 'z': (0, 0, 1)}


def exit_point(g):
    """Where the cable leaves: the RS04's sleeve tip, the RS03's plugs on its rear step's side, the RS00's sockets on its body."""
    r = g['real']
    hub, o, gv = r['hub'], r['out'], r['g']
    m = r['model']
    back = [-v for v in o]
    if m == 'RS04':
        return [hub[i] + back[i] * 0.0458 + gv[i] * 0.0581 for i in range(3)]
    if m == 'RS03':
        return [hub[i] + back[i] * 0.053 + gv[i] * 0.040 for i in range(3)]
    return [hub[i] + back[i] * 0.03 + gv[i] * 0.0285 for i in range(3)]


def nearest_on_axis(j, p):
    o, a = j['origin'], AX[j['axis']]
    t = sum((p[i] - o[i]) * a[i] for i in range(3))
    t = max(-0.06, min(0.06, t))                   # stay by the joint
    return [o[i] + a[i] * t for i in range(3)]


def dist(a, b):
    return math.dist(a, b)


rows = []
for ln, l in links.items():
    for g in l['geoms']:
        if g['role'] != 'actuator' or not g.get('real'):
            continue
        p = exit_point(g)
        pts, crossed, loops = [p], [], 0.0
        k = ln
        while k != 'trunk':
            j = joints[k]
            q = nearest_on_axis(j, pts[-1])
            # the loop sits a bend radius off the axis
            pts.append(q)
            rng = j['upper'] - j['lower']
            loops += rng * R_LOOP                       # what the cable's path round the axis gains over the joint's range, wrapping at its bend radius
            crossed.append(f"{j['name']} ({rng:.2f} rad)")
            k = j['parent']
        last = pts[-1]
        tgt = [min(max(last[i], blo[i]), bhi[i]) for i in range(3)]
        pts.append(tgt)
        L = sum(dist(pts[i], pts[i + 1]) for i in range(len(pts) - 1)) + loops
        rows.append((g['name'].split(' (buy)')[0], g['real']['model'], ln, crossed, L))
rows.sort(key=lambda r: -r[4])
out = ['# Big duck: actuator cables', '', '**NOT SAFE TO BUILD.** Generated by `tools/big_cables.py`: don\'t edit by hand.', '',
       f'Each harness is {HARNESS * 1000:.0f} mm to its XT30 and {CAN * 1000:.0f} more to its CAN plug. Each route below runs from where the cable leaves its actuator, past each joint it crosses near the joint\'s axis, '
       f'to the nearest face of the computer and power board box on the deck, in straight lines, with slack at each joint for its range, wrapping at {R_LOOP * 1000:.0f} mm (range x radius). '
       'It\'s a lower bound: a real route follows the plates and turns corners. Listed, not drawn: nothing here is in the model or checked for clashes.', '',
       f'Bend radius, assumed (RobStride\'s rating for its harness isn\'t read): {R_STATIC * 1000:.0f} mm (4 x its {OD * 1000:.1f} mm) where it\'s tied down, {R_LOOP * 1000:.0f} mm (10 x) in a loop that moves.', '',
       '| Actuator | Model | On | Crosses | Route, at least | Reaches with 350 mm? |', '|---|---|---|---|---|---|']
short = 0
for n, m, ln, cr, L in rows:
    ok = L <= HARNESS + CAN
    short += not ok
    out.append(f"| {n} | {m} | {ln} | {', '.join(cr) or 'none: in the trunk'} | {L * 1000:.0f} mm | {'yes' if ok else f'**no**: {L * 1000 - 350:.0f} mm short'} |")
out += ['', f'**{short} of {len(rows)} don\'t reach.** What that leaves to design: a CAN hub and a power distribution block on each leg (at the hip yaw\'s beam, say, where 8 cables meet), with one 12 AWG pair and one CAN pair across the yaw '
        'and up to the board; or extensions with their own connectors, which add a joint that can work loose in a robot that walks. Neither is in the model. The RS00\'s and RS03s\' plug positions are from their files; '
        'the head\'s and neck\'s routes cross the neck pitch near its axis, inside the neck plates.', '',
        'Not designed: strain relief at each actuator, cable guards past the cranks and rods, ties, and the slots and clips along the plates.']
open(os.path.join(ROOT, 'docs', 'big', 'CABLES.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'{len(rows)} actuators, {short} short of 350 mm -> docs/big/CABLES.md')
for r in rows:
    print(f'  {r[0]:28} {r[4] * 1000:5.0f} mm')

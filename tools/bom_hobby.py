def ribbon_length(spec):
    """The camera's ribbon, face to Pi, along the head's chain, with a 3 cm loop at each joint: 4 joints."""
    J = {j['child']: j for j in spec['joints']}
    cam = next(g for g in spec['links']['head']['geoms'] if g['name'] == 'camera')
    pi = next(g for g in spec['links']['trunk']['geoms'] if g['name'] == 'Pi camera ribbon')
    p, ln, L, n = cam['c'], 'head', 0.0, 0
    while ln != 'trunk':
        q = J[ln]['origin']
        L, p, ln, n = L + math.dist(p, q), q, J[ln]['parent'], n + 1
    return L + math.dist(p, pi['c']) + 0.03 * n, n


